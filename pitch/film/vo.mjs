// Voice-over: one AIFF per shot with macOS `say`, caption chunks timed to the pauses in the audio.
// Writes vo/NN.aiff, vo/vo.txt and vo/timing.js (window.VO, read by film.html and render.mjs).
// Usage: node vo.mjs
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('./vo/', import.meta.url).pathname;
const script = JSON.parse(readFileSync(dir + 'script.json', 'utf8'));
const VOICE = 'Samantha', RATE = '175';

const probe = (f) => parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString());
function silenceList(f) {
  const log = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', f, '-af', 'silencedetect=noise=-38dB:d=0.08', '-f', 'null', '-'], { encoding: 'utf8' }).stderr;
  const out = []; let s = null;
  for (const line of log.split('\n')) {
    const a = line.match(/silence_start: ([\d.]+)/); if (a) s = parseFloat(a[1]);
    const b = line.match(/silence_end: ([\d.]+)/); if (b && s != null) { out.push([s, parseFloat(b[1])]); s = null; }
  }
  return out;
}

const VO = [];
const txt = [];
for (const line of script) {
  const file = `${dir}${line.id}.aiff`;
  execFileSync('say', ['-v', VOICE, '-r', RATE, '-o', file, line.say]);
  const dur = probe(file);
  const sil = silenceList(file).filter(([a, b]) => a > 0.15 && b < dur - 0.1);
  const weights = line.captions.map((c) => c.length + 10 * (c.match(/\$?\d[\d,]*/g) || []).length);
  const total = weights.reduce((a, b) => a + b, 0);
  const lead = (silenceList(file)[0] || [0, 0]);
  const speechStart = lead[0] < 0.05 ? lead[1] : 0;
  const bounds = []; // [end of chunk i, start of chunk i+1]
  let acc = 0, used = -1;
  for (let i = 0; i < line.captions.length - 1; i++) {
    acc += weights[i];
    const expect = speechStart + (dur - speechStart) * (acc / total);
    // A chunk that ends mid-sentence (no punctuation) has no pause to snap to: split by length.
    if (!/[.,;:!?]$/.test(line.captions[i])) { bounds.push([expect, expect]); continue; }
    let best = -1, bd = 1e9;
    sil.forEach(([a, b], k) => { if (k <= used) return; const d = Math.abs((a + b) / 2 - expect); if (d < bd) { bd = d; best = k; } });
    if (best >= 0 && bd < 1.6) { bounds.push(sil[best]); used = best; } else bounds.push([expect, expect]);
  }
  const caps = line.captions.map((text, i) => ({
    text,
    s: +(line.start + (i === 0 ? speechStart : bounds[i - 1][1])).toFixed(3),
    e: +(line.start + (i === line.captions.length - 1 ? dur : bounds[i][0])).toFixed(3),
  }));
  VO.push({ id: line.id, scene: line.scene, start: line.start, dur: +dur.toFixed(3), file: `vo/${line.id}.aiff`, captions: caps });
  txt.push(`${line.id}\t@${line.start.toFixed(1)}s\t${dur.toFixed(2)}s\t${line.say}`);
  console.log(line.id, dur.toFixed(2), caps.map((c) => `${c.s.toFixed(2)}-${c.e.toFixed(2)}`).join(' '));
}
for (let i = 1; i < VO.length; i++) {
  const prevEnd = VO[i - 1].start + VO[i - 1].dur;
  if (prevEnd > VO[i].start) console.warn(`overlap: ${VO[i - 1].id} ends ${prevEnd.toFixed(2)} > ${VO[i].id} starts ${VO[i].start}`);
}
writeFileSync(dir + 'timing.js', `// generated by vo.mjs; do not edit\nwindow.VO = ${JSON.stringify(VO, null, 1)};\n`);
writeFileSync(dir + 'vo.txt', `# Voice-over: say -v ${VOICE} -r ${RATE}; id, start in the film, duration, text\n` + txt.join('\n') + '\n');
